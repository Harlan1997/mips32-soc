linux_retire_env=()
if [[ "${LINUX_RETIRE_TRACE}" == "1" ]]; then
    linux_retire_define=" +define+TB_RETIRE_TRACE"
    linux_retire_env=(RETIRE_TRACE="${sim_dir}/rtl_retire.jsonl")
