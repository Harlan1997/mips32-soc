    RUN_DIR="${sim_dir}" \
    FW_HEX="${RUN_DIR}/image/bootrom.hex" \
    SKIP_COVERAGE="${SKIP_COVERAGE:-0}" \
    VCS_EXTRA_ARGS="+define+SOC_LINUX_BOOT_ENABLE=1 +define+SOC_LINUX_GUEST_ENABLE=1 +define+SOC_PRODUCT_BOOT_ENABLE=1 +define+SOC_MMU_ENABLE=1 +define+TB_LINUX_BOOT +define+TB_LINUX_BOOT_TRACE${linux_retire_define}${linux_l1_observation_define} ${LINUX_VCS_EXTRA_ARGS}" \
    "${linux_retire_env[@]}" \
    SIM_EXTRA_ARGS="+BOOT_ROM_HEX=${RUN_DIR}/image/bootrom.hex +DDR_HEX=${RUN_DIR}/image/ddr.hex +LINUX_TRACE_LIMIT=${RTL_CYCLE_LIMIT} +LINUX_REFILL_TRACE=${LINUX_REFILL_TRACE} +LINUX_PROGRESS_TRACE=${LINUX_PROGRESS_TRACE} +LINUX_EXCEPTION_TRACE=${LINUX_EXCEPTION_TRACE} +LINUX_EBASE_TRACE=${LINUX_EBASE_TRACE} +LINUX_EBASE_TRACE_LIMIT=${LINUX_EBASE_TRACE_LIMIT} +LINUX_WB_TRACE=${LINUX_WB_TRACE} +LINUX_WB_TRACE_LIMIT=${LINUX_WB_TRACE_LIMIT} +LINUX_WAIT_TRACE=${LINUX_WAIT_TRACE} +LINUX_WAIT_TRACE_LIMIT=${LINUX_WAIT_TRACE_LIMIT} +LINUX_TLB_TRACE=${LINUX_TLB_TRACE} +LINUX_TLB_TRACE_LIMIT=${LINUX_TLB_TRACE_LIMIT} +LINUX_TLB_TRACE_CYCLE_START=${LINUX_TLB_TRACE_CYCLE_START} +LINUX_TLB_TRACE_CYCLE_END=${LINUX_TLB_TRACE_CYCLE_END} +LINUX_VECTOR_TRACE=${LINUX_VECTOR_TRACE} +LINUX_VECTOR_TRACE_LIMIT=${LINUX_VECTOR_TRACE_LIMIT} +LINUX_CACHEOP_TRACE_LIMIT=${LINUX_CACHEOP_TRACE_LIMIT} +LINUX_CACHEOP_TRACE_LINE=${LINUX_CACHEOP_TRACE_LINE} +LINUX_CP0_TRACE_LIMIT=${LINUX_CP0_TRACE_LIMIT} +LINUX_VECTOR_LINE_TRACE=${LINUX_VECTOR_LINE_TRACE} +LINUX_VECTOR_LINE_TRACE_LIMIT=${LINUX_VECTOR_LINE_TRACE_LIMIT} +LINUX_VECTOR_LINE=${LINUX_VECTOR_LINE} +LINUX_DELAY_TRACE=${LINUX_DELAY_TRACE} +LINUX_DELAY_TRACE_LIMIT=${LINUX_DELAY_TRACE_LIMIT} +LINUX_DELAY_TRACE_START=${LINUX_DELAY_TRACE_START} +LINUX_DELAY_TRACE_END=${LINUX_DELAY_TRACE_END} +LINUX_DELAY_TRACE_CYCLE_START=${LINUX_DELAY_TRACE_CYCLE_START} +LINUX_DELAY_TRACE_CYCLE_END=${LINUX_DELAY_TRACE_CYCLE_END} +LINUX_TARGET_DSIDE_TRACE=${LINUX_TARGET_DSIDE_TRACE} +LINUX_TARGET_DSIDE_TRACE_LIMIT=${LINUX_TARGET_DSIDE_TRACE_LIMIT} +LINUX_TARGET_TRACE_LINE=${LINUX_TARGET_TRACE_LINE} +LINUX_TARGET_TRACE_CYCLE_START=${LINUX_TARGET_TRACE_CYCLE_START} +LINUX_TARGET_TRACE_CYCLE_END=${LINUX_TARGET_TRACE_CYCLE_END} +LINUX_UART_TRACE=${LINUX_UART_TRACE} +LINUX_UART_TRACE_LIMIT=${LINUX_UART_TRACE_LIMIT} +LINUX_VIC_TRACE=${LINUX_VIC_TRACE} +LINUX_VIC_TRACE_LIMIT=${LINUX_VIC_TRACE_LIMIT} +LINUX_PANIC_TRACE=${LINUX_PANIC_TRACE} +LINUX_PANIC_TRACE_LIMIT=${LINUX_PANIC_TRACE_LIMIT} +LINUX_PANIC_TRACE_START=${LINUX_PANIC_TRACE_START} +LINUX_PANIC_TRACE_END=${LINUX_PANIC_TRACE_END}" \
    LINUX_EXTRA_SIM_ARGS="+LINUX_GPR_TRACE=${LINUX_GPR_TRACE} +LINUX_GPR_TRACE_LIMIT=${LINUX_GPR_TRACE_LIMIT} +LINUX_GPR_TRACE_REG=${LINUX_GPR_TRACE_REG} +LINUX_GPR_TRACE_CYCLE_START=${LINUX_GPR_TRACE_CYCLE_START} +LINUX_GPR_TRACE_CYCLE_END=${LINUX_GPR_TRACE_CYCLE_END} +LINUX_CACHE_OWNER_TRACE=${LINUX_CACHE_OWNER_TRACE} +LINUX_CACHE_OWNER_TRACE_LIMIT=${LINUX_CACHE_OWNER_TRACE_LIMIT} +LINUX_EXCEPTION_TRACE_LIMIT=${LINUX_EXCEPTION_TRACE_LIMIT} +LINUX_EXCEPTION_FRAME_TRACE=${LINUX_EXCEPTION_FRAME_TRACE} +LINUX_EXCEPTION_FRAME_TRACE_LIMIT=${LINUX_EXCEPTION_FRAME_TRACE_LIMIT} +LINUX_EXCEPTION_FRAME_TRACE_CYCLE_START=${LINUX_EXCEPTION_FRAME_TRACE_CYCLE_START} +LINUX_EXCEPTION_FRAME_TRACE_CYCLE_END=${LINUX_EXCEPTION_FRAME_TRACE_CYCLE_END} +LINUX_FAULT_TRACE=${LINUX_FAULT_TRACE} +LINUX_FAULT_TRACE_LIMIT=${LINUX_FAULT_TRACE_LIMIT} +LINUX_FAULT_TRACE_START=${LINUX_FAULT_TRACE_START} +LINUX_FAULT_TRACE_END=${LINUX_FAULT_TRACE_END} +LINUX_FAULT_TRACE_CYCLE_START=${LINUX_FAULT_TRACE_CYCLE_START} +LINUX_FAULT_TRACE_CYCLE_END=${LINUX_FAULT_TRACE_CYCLE_END} +LINUX_EBASE_TRACE=${LINUX_EBASE_TRACE} +LINUX_EBASE_TRACE_LIMIT=${LINUX_EBASE_TRACE_LIMIT} +LINUX_WB_TRACE=${LINUX_WB_TRACE} +LINUX_WB_TRACE_LIMIT=${LINUX_WB_TRACE_LIMIT} +LINUX_VECTOR_TRACE=${LINUX_VECTOR_TRACE} +LINUX_PANIC_TRACE_START=${LINUX_PANIC_TRACE_START} +LINUX_MODE_TRACE=${LINUX_MODE_TRACE} +LINUX_MODE_TRACE_LIMIT=${LINUX_MODE_TRACE_LIMIT} +LINUX_PC_TRACE=${LINUX_PC_TRACE} +LINUX_PC_TRACE_LIMIT=${LINUX_PC_TRACE_LIMIT} +LINUX_PC_TRACE_RETIRE_ONLY=${LINUX_PC_TRACE_RETIRE_ONLY} +LINUX_PC_TRACE_SYMBOL=${LINUX_PC_TRACE_SYMBOL} +LINUX_PC_TRACE_START=${LINUX_PC_TRACE_START} +LINUX_PC_TRACE_END=${LINUX_PC_TRACE_END} +RETIRE_TRACE_MAX_RECORDS=${LINUX_RETIRE_TRACE_MAX_RECORDS} +LINUX_PC_TRACE_CYCLE_START=${LINUX_PC_TRACE_CYCLE_START} +LINUX_PC_TRACE_CYCLE_END=${LINUX_PC_TRACE_CYCLE_END} +LINUX_STALL_TRACE=${LINUX_STALL_TRACE} +LINUX_STALL_TRACE_LIMIT=${LINUX_STALL_TRACE_LIMIT} +LINUX_STALL_TRACE_CYCLE_START=${LINUX_STALL_TRACE_CYCLE_START} +LINUX_STALL_TRACE_PC=${LINUX_STALL_TRACE_PC}${linux_seed_arg}" \
    LINUX_APB_SIM_ARGS="+LINUX_APB_TRACE=${LINUX_APB_TRACE} +LINUX_APB_TRACE_LIMIT=${LINUX_APB_TRACE_LIMIT} +LINUX_APB_SELECT_TRACE=${LINUX_APB_SELECT_TRACE} +LINUX_APB_SELECT_TRACE_LIMIT=${LINUX_APB_SELECT_TRACE_LIMIT}" \
    "${ROOT_DIR}/tb/soc_test/run.sh" >"${RUN_DIR}/sim.log" 2>&1
status=$?
set -e

if [[ "${status}" -ne 0 ]]; then
    echo "RTL Linux progress gate: simulator command failed or timed out (status ${status})" >&2
    exit "${status}"
fi

test -s "${sim_dir}/sim.log" || {
    echo "RTL Linux progress gate: simulator log is missing" >&2
    exit 1
}

# A bounded probe is useful only when it demonstrates post-boot instruction
# progress.  It is deliberately not a boot gate: userspace and its success
# marker are checked by the future RTL Linux boot gate.
if [[ "${LINUX_REQUIRE_PROGRESS}" == "1" ]] &&
   ! rg -q 'LINUX_PROGRESS_TRACE cycle=[1-9][0-9]* pc=(?!bfc00000)' \
        --pcre2 "${sim_dir}/sim.log"; then
    echo "RTL Linux progress gate: no post-reset CPU progress observed (status ${status})" >&2
    exit 1
fi
if rg -q 'REGRESSION_TEST_FAILED|Comprehensive SoC Test Failed|tb_mips_soc: ERROR' \
        "${sim_dir}/sim.log"; then
    echo "RTL Linux progress gate: simulator reported a regression failure" >&2
    exit 1
fi

marker_count=$(rg -c 'MIPS32_SOC_LINUX_BOOT_SUCCESS' "${sim_dir}/sim.log" || echo 0)
result="PASS (bounded post-reset progress probe)"
if [[ "${LINUX_REQUIRE_USERSPACE}" == "1" && "${marker_count}" -eq 0 ]]; then
    result="FAIL (Linux userspace marker not observed)"
fi
cat >"${RUN_DIR}/completion_report.md" <<EOF
# RTL Linux Progress Gate

- Result: ${result}
- Host timeout: ${HOST_TIMEOUT}
- RTL cycle limit: ${RTL_CYCLE_LIMIT}
- RTL simulation seed: ${RTL_SIM_SEED:-default}
- Linux profile: ${LINUX_PROFILE}
- Delay trace: ${LINUX_DELAY_TRACE} (limit=${LINUX_DELAY_TRACE_LIMIT}, window=${LINUX_DELAY_TRACE_START}..${LINUX_DELAY_TRACE_END})
- UART trace: ${LINUX_UART_TRACE} (limit=${LINUX_UART_TRACE_LIMIT})
- APB trace: ${LINUX_APB_TRACE} (limit=${LINUX_APB_TRACE_LIMIT})
- APB select trace: ${LINUX_APB_SELECT_TRACE} (limit=${LINUX_APB_SELECT_TRACE_LIMIT})
- VIC trace: ${LINUX_VIC_TRACE} (limit=${LINUX_VIC_TRACE_LIMIT})
- Panic trace: ${LINUX_PANIC_TRACE} (limit=${LINUX_PANIC_TRACE_LIMIT})
- Panic trace window: ${LINUX_PANIC_TRACE_START}..${LINUX_PANIC_TRACE_END}
- Fault/address trace: ${LINUX_FAULT_TRACE} (limit=${LINUX_FAULT_TRACE_LIMIT}, window=${LINUX_FAULT_TRACE_START}..${LINUX_FAULT_TRACE_END}, cycles=${LINUX_FAULT_TRACE_CYCLE_START}..${LINUX_FAULT_TRACE_CYCLE_END})
- Exception-frame trace: ${LINUX_EXCEPTION_FRAME_TRACE} (limit=${LINUX_EXCEPTION_FRAME_TRACE_LIMIT}, cycles=${LINUX_EXCEPTION_FRAME_TRACE_CYCLE_START}..${LINUX_EXCEPTION_FRAME_TRACE_CYCLE_END})
- GPR trace: ${LINUX_GPR_TRACE} (reg=${LINUX_GPR_TRACE_REG}, limit=${LINUX_GPR_TRACE_LIMIT}, cycles=${LINUX_GPR_TRACE_CYCLE_START}..${LINUX_GPR_TRACE_CYCLE_END})
- Cache owner trace: ${LINUX_CACHE_OWNER_TRACE} (limit=${LINUX_CACHE_OWNER_TRACE_LIMIT}, line=${LINUX_TARGET_TRACE_LINE})
