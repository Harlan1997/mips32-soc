LINUX_VECTOR_LINE_TRACE=${LINUX_VECTOR_LINE_TRACE:-0}
LINUX_VECTOR_LINE_TRACE_LIMIT=${LINUX_VECTOR_LINE_TRACE_LIMIT:-256}
LINUX_VECTOR_LINE=${LINUX_VECTOR_LINE:-470410}
SKIP_LINUX_BUILD=${SKIP_LINUX_BUILD:-0}
KERNEL_INPUT=${KERNEL:-}

# Progress is the evidence source for the post-reset progress criterion.  Do
# not spend a long simulator run only to reject it after completion when the
# caller explicitly disabled that trace.
if [[ "${LINUX_REQUIRE_PROGRESS}" == "1" &&
      "${LINUX_PROGRESS_TRACE}" != "1" ]]; then
    echo "RTL Linux progress gate: LINUX_REQUIRE_PROGRESS=1 requires LINUX_PROGRESS_TRACE=1" >&2
    exit 2
fi

# VCS warns and may truncate a %h plusarg when the payload includes 0x.
# Normalize trace addresses before forwarding them to the Verilog testbench.
strip_hex_prefix() {
    local value=${1:-}
    value=${value#0x}
    value=${value#0X}
    printf '%s' "${value}"
}

mkdir -p "${RUN_DIR}"

# Build a self-contained relocated image.  Keeping the kernel, DTB, Boot ROM,
# DDR image and simulator in one run directory makes this probe reproducible
# and avoids accidentally reusing an image from a different address layout.
if [[ "${SKIP_LINUX_BUILD}" == "1" || -n "${KERNEL_INPUT}" ]]; then
    if [[ "${SKIP_LINUX_BUILD}" == "1" && -z "${KERNEL_INPUT}" ]]; then
        echo "SKIP_LINUX_BUILD=1 requires KERNEL=/path/to/vmlinux" >&2
        exit 1
    fi
    if [[ -z "${KERNEL_INPUT}" ]]; then
        echo "RTL Linux progress gate: no KERNEL supplied for build skip" >&2
        exit 1
    fi
    test -s "${KERNEL_INPUT}"
    KERNEL_PATH=$(realpath "${KERNEL_INPUT}")
    printf 'Linux kernel build: SKIPPED (reusing supplied KERNEL)\nKERNEL=%s\n' "${KERNEL_PATH}" >"${RUN_DIR}/build.log"
else
    BUILD_DIR="${RUN_DIR}" JOBS="${JOBS}" KERNEL_PHYSICAL_START="${KERNEL_PHYSICAL_START}" \
        LINUX_PROFILE="${LINUX_PROFILE}" \
        "${SCRIPT_DIR}/build_linux_boot.sh" >"${RUN_DIR}/build.log" 2>&1
    KERNEL_PATH="${RUN_DIR}/kernel/vmlinux"
fi

# The kernel symbol layout changes with relocation and configuration. Resolve
# the bounded panic diagnostic window from the actual ELF instead of keeping a
# stale hard-coded address from an older image.
if [[ -z "${LINUX_PANIC_TRACE_START}" ]] && command -v "${CROSS_COMPILE}nm" >/dev/null 2>&1; then
    panic_symbol=$(${CROSS_COMPILE}nm -n "${KERNEL_PATH}" 2>/dev/null |
        awk '$3 == "panic" && !found { print $1; found = 1 }')
    if [[ "${panic_symbol}" =~ [0-9a-fA-F]{8}$ ]]; then
        panic_low=${panic_symbol: -8}
        LINUX_PANIC_TRACE_START="0x${panic_low}"
        panic_start_value=$((16#${panic_low}))
        LINUX_PANIC_TRACE_END=$(printf '0x%08x' $((panic_start_value + 0x400)))
    fi
fi
LINUX_PANIC_TRACE_START=${LINUX_PANIC_TRACE_START:-0x89245cbc}
LINUX_PANIC_TRACE_END=${LINUX_PANIC_TRACE_END:-0x89246010}
# Resolve a bounded function window from the supplied ELF when the caller
# enables PC tracing without explicit addresses.
if [[ "${LINUX_PC_TRACE}" == "1" && -z "${LINUX_PC_TRACE_START}" &&
      -z "${LINUX_PC_TRACE_END}" ]] && command -v "${CROSS_COMPILE}nm" >/dev/null 2>&1; then
    pc_symbol=$(${CROSS_COMPILE}nm -n "${KERNEL_PATH}" 2>/dev/null |
        awk -v symbol="${LINUX_PC_TRACE_SYMBOL}" '$3 == symbol && !found { print $1; found = 1 }')
    if [[ "${pc_symbol}" =~ [0-9a-fA-F]{8}$ ]]; then
        pc_low=${pc_symbol: -8}
        LINUX_PC_TRACE_START="0x${pc_low}"
        pc_start_value=$((16#${pc_low}))
        LINUX_PC_TRACE_END=$(printf '0x%08x' $((pc_start_value + 0x400)))
    fi
fi
LINUX_PC_TRACE_START=${LINUX_PC_TRACE_START:-0x00000000}
LINUX_PC_TRACE_END=${LINUX_PC_TRACE_END:-0x00000000}
LINUX_PC_TRACE_START=$(strip_hex_prefix "${LINUX_PC_TRACE_START}")
LINUX_PC_TRACE_END=$(strip_hex_prefix "${LINUX_PC_TRACE_END}")
LINUX_PANIC_TRACE_START=$(strip_hex_prefix "${LINUX_PANIC_TRACE_START}")
LINUX_PANIC_TRACE_END=$(strip_hex_prefix "${LINUX_PANIC_TRACE_END}")
LINUX_STALL_TRACE_PC=$(strip_hex_prefix "${LINUX_STALL_TRACE_PC}")
LINUX_CACHEOP_TRACE_LINE=$(strip_hex_prefix "${LINUX_CACHEOP_TRACE_LINE}")
LINUX_TARGET_TRACE_LINE=$(strip_hex_prefix "${LINUX_TARGET_TRACE_LINE}")
LINUX_DELAY_TRACE_START=$(strip_hex_prefix "${LINUX_DELAY_TRACE_START}")
LINUX_DELAY_TRACE_END=$(strip_hex_prefix "${LINUX_DELAY_TRACE_END}")
LINUX_FAULT_TRACE_START=$(strip_hex_prefix "${LINUX_FAULT_TRACE_START}")
LINUX_FAULT_TRACE_END=$(strip_hex_prefix "${LINUX_FAULT_TRACE_END}")
LINUX_VECTOR_LINE=$(strip_hex_prefix "${LINUX_VECTOR_LINE}")
KERNEL="${KERNEL_PATH}" \
    DTC="$(dirname "${KERNEL_PATH}")/scripts/dtc/dtc" \
    RUN_DIR="${RUN_DIR}/image" \
    "${SCRIPT_DIR}/build_rtl_linux_image.sh" >"${RUN_DIR}/image.log" 2>&1

if [[ ! -s "${RUN_DIR}/image/bootrom.hex" ||
      ! -s "${RUN_DIR}/image/ddr.hex" ]]; then
    echo "RTL Linux progress gate: image generation did not produce bootrom/ddr hex" >&2
    exit 1
fi

sim_dir="${RUN_DIR}/sim"
mkdir -p "${sim_dir}"
