if [[ " ${LINUX_VCS_EXTRA_ARGS} " == *" +define+SOC_CPU_NONBLOCKING_ENABLE=1 "* &&
      " ${LINUX_VCS_EXTRA_ARGS} " == *" +define+SOC_L1_NONBLOCKING_ENABLE=1 "* ]]; then
    linux_l1_observation_define=" +define+TB_L1_NONBLOCKING"
fi
linux_seed_arg=""
if [[ -n "${RTL_SIM_SEED}" ]]; then
    linux_seed_arg=" +ntb_random_seed=${RTL_SIM_SEED}"
fi
