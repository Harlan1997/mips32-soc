LINUX_STALL_TRACE_PC=${LINUX_STALL_TRACE_PC:-0}
LINUX_REQUIRE_PROGRESS=${LINUX_REQUIRE_PROGRESS:-1}
LINUX_REQUIRE_USERSPACE=${LINUX_REQUIRE_USERSPACE:-0}
LINUX_EXCEPTION_TRACE=${LINUX_EXCEPTION_TRACE:-0}
